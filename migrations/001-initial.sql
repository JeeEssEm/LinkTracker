BEGIN;

CREATE TABLE chats
(
    id         bigint,
    created_at TIMESTAMP DEFAULT (now() AT TIME ZONE 'utc'),
    CONSTRAINT pk_chats PRIMARY KEY (id)
);

CREATE TABLE links
(
    id            uuid DEFAULT gen_random_uuid(),
    url           character varying(2048) NOT NULL,
    source_type   smallint                NOT NULL,
    last_check_at timestamp with time zone,
    CONSTRAINT pk_links PRIMARY KEY (id)
);

CREATE TABLE subscriptions
(
    chat_id bigint NOT NULL,
    link_id uuid   NOT NULL,
    CONSTRAINT pk_subscriptions PRIMARY KEY (chat_id, link_id),
    CONSTRAINT fk_subscriptions_chats_chat_id FOREIGN KEY (chat_id) REFERENCES chats (id) ON DELETE CASCADE,
    CONSTRAINT fk_subscriptions_links_link_id FOREIGN KEY (link_id) REFERENCES links (id) ON DELETE CASCADE
);

CREATE TABLE tags
(
    id      bigint GENERATED BY DEFAULT AS IDENTITY,
    name    character varying(64) NOT NULL,
    chat_id bigint                NOT NULL,
    link_id uuid                  NOT NULL,
    CONSTRAINT pk_tags PRIMARY KEY (id),
    CONSTRAINT fk_tags_subscriptions FOREIGN KEY (chat_id, link_id) REFERENCES subscriptions (chat_id, link_id) ON DELETE CASCADE,
    CONSTRAINT fk_link_tags_links_link_id FOREIGN KEY (link_id) REFERENCES links (id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX ix_links_url ON links (url);
CREATE INDEX ix_subscriptions_link_id ON subscriptions (link_id);
CREATE INDEX ix_tags_chat_id ON tags (chat_id);
CREATE INDEX ix_links_last_check_at ON links (last_check_at);

COMMIT;
